/** Field order for Xiaomi sport summaries, taken from Mi Fitness 3.59.1 binary schemas. */
object SportReportLayouts {
    @JvmStatic
    fun layout(activity: Int, version: Int): Layout? = when (activity * 1000 + version) {
        22008 -> A22_V8
        22009 -> A22_V9
        23005 -> withoutLeadingSubSport(A23_V8)
        23008 -> A23_V8
        23009 -> A23_V9
        3013 -> A3_V13
        3014 -> A3_V14
        8008 -> A8_V8
        8011 -> A8_V11
        8012 -> A8_V12
        8013 -> A8_V13
        8014 -> A8_V14
        14007 -> A14_V7
        9008 -> A9_V8
        else -> null
    }

    class Field(
        @JvmField val name: String,
        @JvmField val bytes: Int,
        @JvmField val floating: Boolean,
        @JvmField val gate: String?,
        @JvmField val `when`: String?,
        @JvmField val values: IntArray?,
    )

    /** Band 8 Pro v5 reports use the v8 field order but have no leading sub-sport flag. */
    private fun withoutLeadingSubSport(source: Layout): Layout {
        val flags = source.flags.copyOfRange(1, source.flags.size)
        val fields = source.fields.copyOfRange(1, source.fields.size)
        return Layout(source.validityBytes, flags, fields)
    }

